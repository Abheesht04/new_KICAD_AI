"""Reproducible tiny semantic classifier; training only requires PyTorch.
C inference has no dependencies. This is NOT a generative electronics model.
"""
import random, re, json
from pathlib import Path
import torch
from torch import nn
ROOT=Path(__file__).resolve().parents[1]
random.seed(17);torch.manual_seed(17);torch.set_num_threads(2)
classes=[['resistor','resistance','resistive load','ohmic load'],['capacitor','capacitance','decoupling capacitor','bypass capacitor'],['inductor','inductance','choke','coil'],['diode','rectifier','schottky diode'],['led','light emitting diode','indicator led'],['connector','header','terminal block','socket'],['voltage source','dc supply','battery'],['transistor','mosfet','bjt','switching transistor'],['integrated circuit','microcontroller','opamp','amplifier chip'],['banana','weather','hello','music','delete files','unknown device','board','make something','resistor capacitor','resistor diode']]
prefixes=['','make a','add a','i need a','please find a','give me a','create a','use a','select a','insert a']
suffixes=['',' for my circuit',' for this board',' component',' please',' part']
samples=[(f'{a} {b} {c}'.strip(),i) for i,words in enumerate(classes) for a in prefixes for b in words for c in suffixes]
random.shuffle(samples)
vocab=['<pad>','<unk>']+sorted({w for s,_ in samples for w in re.findall('[a-z]+',s)})
def tokens(s):return [vocab.index(w) if w in vocab else 1 for w in re.findall('[a-z]+',s)][:24]
x=torch.zeros((len(samples),24),dtype=torch.long);y=torch.tensor([i for _,i in samples])
for i,(s,_) in enumerate(samples): t=tokens(s);x[i,:len(t)]=torch.tensor(t)
class Model(nn.Module):
 def __init__(self):
  super().__init__();self.emb=nn.Embedding(len(vocab),24);self.q=nn.Linear(24,24,bias=False);self.k=nn.Linear(24,24,bias=False);self.v=nn.Linear(24,24,bias=False);self.o=nn.Linear(24,24,bias=False);self.f1=nn.Linear(24,48);self.f2=nn.Linear(48,24);self.cls=nn.Linear(24,10)
 def forward(self,x):
  mask=x!=0;z=self.emb(x);a=self.q(z)@self.k(z).transpose(1,2)/(24**.5);a=a.masked_fill(~mask[:,None,:],-1e9);h=z+self.o(a.softmax(-1)@self.v(z));h=h+self.f2(torch.relu(self.f1(h)));pooled=(h*mask[:,:,None]).sum(1)/mask.sum(1)[:,None];return self.cls(pooled)
m=Model();opt=torch.optim.Adam(m.parameters(),lr=.003)
for epoch in range(65):
 for ix in torch.randperm(len(x)).split(128):
  opt.zero_grad();loss=nn.functional.cross_entropy(m(x[ix]),y[ix]);loss.backward();opt.step()
with torch.no_grad(): acc=(m(x).argmax(-1)==y).float().mean().item()
# Export row-major weights. C implements exactly this attention/residual/FFN graph.
out=['/* Generated by tools/train_intent.py; seed 17. */',f'#define CT_VOCAB {len(vocab)}','static const char *ct_vocab[]={'+','.join(json.dumps(w) for w in vocab)+'};']
for name,p in m.state_dict().items():
 values=p.detach().flatten().tolist();out.append('static const float ct_'+name.replace('.','_')+'[]={'+','.join(f'{v:.9e}f' for v in values)+'};')
(ROOT/'src/v2/intent_weights.h').write_text('\n'.join(out)+'\n')
(ROOT/'models/training.json').write_text(json.dumps({'seed':17,'samples':len(samples),'training_accuracy':acc,'architecture':'24-dimensional single-head self attention, residual FFN 48, mean pooling, 10 labels','warning':'Training accuracy is not independent language generalization. Reject unknown tokens/categories and mixed roles; proposals require deterministic validation.'},indent=2))
print('trained',len(samples),'accuracy',acc)
